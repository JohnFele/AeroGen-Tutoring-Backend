revoke all on public.subjects, public.tutor_applications, public.tutor_application_subjects,
  public.tutor_profiles, public.tutor_subjects, public.tutor_application_documents,
  public.bookings, public.reviews, public.conversations, public.conversation_members,
  public.messages, public.payments, public.user_notification_preferences, public.notifications
  from anon, authenticated;

grant select on public.subjects, public.tutor_profiles, public.tutor_subjects, public.reviews to anon, authenticated;
grant select, insert on public.tutor_applications to authenticated;
grant select, insert, delete on public.tutor_application_subjects to authenticated;
grant select, insert on public.tutor_application_documents to authenticated;
grant select on public.bookings, public.payments, public.conversations, public.conversation_members,
  public.messages, public.notifications to authenticated;
grant select, insert, update on public.user_notification_preferences to authenticated;
grant usage, select on sequence public.subjects_id_seq to anon, authenticated;

create policy "Active subjects are visible"
  on public.subjects for select to anon, authenticated using (is_active);
create policy "Approved tutors are discoverable"
  on public.tutor_profiles for select to anon, authenticated using (is_approved and is_accepting_students);
create policy "Subjects of approved tutors are discoverable"
  on public.tutor_subjects for select to anon, authenticated using (
    exists (select 1 from public.tutor_profiles tp where tp.user_id = tutor_id and tp.is_approved and tp.is_accepting_students)
  );
create policy "Published reviews are visible"
  on public.reviews for select to anon, authenticated using (
    is_published and exists (select 1 from public.tutor_profiles tp where tp.user_id = tutor_id and tp.is_approved)
  );

create policy "Applicants can read their applications"
  on public.tutor_applications for select to authenticated using ((select auth.uid()) = user_id);
create policy "Applicants can submit their applications"
  on public.tutor_applications for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "Applicants can read their application subjects"
  on public.tutor_application_subjects for select to authenticated using (
    exists (select 1 from public.tutor_applications a where a.id = application_id and a.user_id = (select auth.uid()))
  );
create policy "Applicants can attach subjects to their applications"
  on public.tutor_application_subjects for insert to authenticated with check (
    exists (select 1 from public.tutor_applications a where a.id = application_id and a.user_id = (select auth.uid()))
  );
create policy "Applicants can remove subjects from their applications"
  on public.tutor_application_subjects for delete to authenticated using (
    exists (select 1 from public.tutor_applications a where a.id = application_id and a.user_id = (select auth.uid()))
  );
create policy "Applicants can read their document metadata"
  on public.tutor_application_documents for select to authenticated using (
    left(storage_path, length((select auth.uid())::text) + 1) = (select auth.uid())::text || '/'
    and exists (select 1 from public.tutor_applications a where a.id = application_id and a.user_id = (select auth.uid()))
  );
create policy "Applicants can register document metadata"
  on public.tutor_application_documents for insert to authenticated with check (
    left(storage_path, length((select auth.uid())::text) + 1) = (select auth.uid())::text || '/'
    and exists (select 1 from public.tutor_applications a where a.id = application_id and a.user_id = (select auth.uid()))
  );

create policy "Booking participants can read bookings"
  on public.bookings for select to authenticated using ((select auth.uid()) in (student_id, tutor_id));
create policy "Booking participants can read payments"
  on public.payments for select to authenticated using ((select auth.uid()) in (payer_id, payee_id));
create policy "Conversation members can read conversations"
  on public.conversations for select to authenticated using (
    exists (select 1 from public.conversation_members cm where cm.conversation_id = id and cm.user_id = (select auth.uid()))
  );
create policy "Users can read their conversation memberships"
  on public.conversation_members for select to authenticated using (user_id = (select auth.uid()));
create policy "Conversation members can read messages"
  on public.messages for select to authenticated using (
    exists (select 1 from public.conversation_members cm where cm.conversation_id = messages.conversation_id and cm.user_id = (select auth.uid()))
  );
create policy "Users can read their notifications"
  on public.notifications for select to authenticated using (user_id = (select auth.uid()));
create policy "Users can manage their notification preferences"
  on public.user_notification_preferences for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

-- Private bucket for identity and qualification files. Store objects under
-- <auth.uid()>/<application-id>/<filename> so the first path segment is verifiable.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'tutor-application-documents',
  'tutor-application-documents',
  false,
  10485760,
  array['application/pdf', 'image/jpeg', 'image/png']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

create policy "Applicants can view their private application files"
  on storage.objects for select to authenticated using (
    bucket_id = 'tutor-application-documents'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );
create policy "Applicants can upload their private application files"
  on storage.objects for insert to authenticated with check (
    bucket_id = 'tutor-application-documents'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

