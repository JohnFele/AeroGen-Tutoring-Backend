-- Marketplace data model for AeroGen Tutoring.
-- Profile/auth identity is owned by Supabase Auth and the earlier profiles migration.

create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  name text not null unique,
  category text not null,
  slug text not null unique,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.tutor_applications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'submitted'
    check (status in ('draft', 'submitted', 'under_review', 'approved', 'rejected', 'withdrawn')),
  phone text,
  street_address text,
  city text,
  province text check (province is null or province in (
    'Eastern Cape', 'Free State', 'Gauteng', 'KwaZulu-Natal', 'Limpopo',
    'Mpumalanga', 'North West', 'Northern Cape', 'Western Cape'
  )),
  highest_qualification text,
  institution text,
  year_completed smallint check (year_completed is null or year_completed between 1900 and 2200),
  certifications text,
  years_experience numeric(4,1) check (years_experience is null or years_experience >= 0),
  previous_platforms text,
  student_age_groups text[] not null default '{}',
  teaching_style text,
  availability_slots text[] not null default '{}',
  teaching_modes text[] not null default '{}'
    check (teaching_modes <@ array['online', 'in-person']::text[]),
  hourly_rate numeric(10,2) check (hourly_rate is null or hourly_rate > 0),
  students_per_session text,
  submitted_at timestamptz,
  reviewed_at timestamptz,
  reviewer_id uuid references public.profiles(id) on delete set null,
  review_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists tutor_applications_user_created_idx
  on public.tutor_applications (user_id, created_at desc);
create index if not exists tutor_applications_status_created_idx
  on public.tutor_applications (status, created_at desc);

create table if not exists public.tutor_application_subjects (
  application_id uuid not null references public.tutor_applications(id) on delete cascade,
  subject_id bigint not null references public.subjects(id) on delete restrict,
  primary key (application_id, subject_id)
);

create table if not exists public.tutor_profiles (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  public_name text,
  bio text not null default '',
  city text,
  province text,
  qualification text,
  institution text,
  year_completed smallint check (year_completed is null or year_completed between 1900 and 2200),
  certifications text,
  years_experience numeric(4,1) check (years_experience is null or years_experience >= 0),
  teaching_style text,
  student_age_groups text[] not null default '{}',
  availability_slots text[] not null default '{}',
  teaching_modes text[] not null default '{}'
    check (teaching_modes <@ array['online', 'in-person']::text[]),
  hourly_rate numeric(10,2) check (hourly_rate is null or hourly_rate > 0),
  students_per_session text,
  is_approved boolean not null default false,
  is_accepting_students boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists tutor_profiles_discovery_idx
  on public.tutor_profiles (is_approved, is_accepting_students, province, city);

create table if not exists public.tutor_subjects (
  tutor_id uuid not null references public.tutor_profiles(user_id) on delete cascade,
  subject_id bigint not null references public.subjects(id) on delete restrict,
  primary key (tutor_id, subject_id)
);
create index if not exists tutor_subjects_subject_idx on public.tutor_subjects (subject_id, tutor_id);

create table if not exists public.tutor_application_documents (
  id uuid primary key default gen_random_uuid(),
  application_id uuid not null references public.tutor_applications(id) on delete cascade,
  document_type text not null check (document_type in ('identity', 'qualification', 'resume')),
  storage_path text not null unique,
  original_filename text,
  mime_type text,
  size_bytes bigint check (size_bytes is null or size_bytes >= 0),
  created_at timestamptz not null default now(),
  unique (application_id, document_type)
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.profiles(id) on delete restrict,
  tutor_id uuid not null references public.tutor_profiles(user_id) on delete restrict,
  subject_id bigint references public.subjects(id) on delete set null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  timezone text not null default 'Africa/Johannesburg',
  status text not null default 'pending'
    check (status in ('pending', 'confirmed', 'completed', 'cancelled', 'declined', 'no_show')),
  teaching_mode text not null check (teaching_mode in ('online', 'in-person')),
  session_type text not null default 'individual'
    check (session_type in ('individual', 'small-group', 'medium-group')),
  duration_minutes smallint not null check (duration_minutes in (30, 60, 90, 120)),
  hourly_rate numeric(10,2) not null check (hourly_rate > 0),
  total_amount numeric(10,2) not null check (total_amount > 0),
  currency char(3) not null default 'ZAR' check (currency = 'ZAR'),
  special_requests text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at > starts_at),
  check (ends_at - starts_at = make_interval(mins => duration_minutes))
);
create index if not exists bookings_student_schedule_idx on public.bookings (student_id, starts_at desc);
create index if not exists bookings_tutor_schedule_idx on public.bookings (tutor_id, starts_at desc);
create index if not exists bookings_status_schedule_idx on public.bookings (status, starts_at);

create table if not exists public.reviews (
  id uuid primary key default gen_random_uuid(),
  booking_id uuid not null unique references public.bookings(id) on delete restrict,
  student_id uuid not null references public.profiles(id) on delete restrict,
  tutor_id uuid not null references public.tutor_profiles(user_id) on delete restrict,
  rating smallint not null check (rating between 1 and 5),
  body text,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists reviews_tutor_published_idx on public.reviews (tutor_id, created_at desc) where is_published;

create table if not exists public.conversations (
  id uuid primary key default gen_random_uuid(),
  booking_id uuid references public.bookings(id) on delete set null,
  created_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.conversation_members (
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  joined_at timestamptz not null default now(),
  last_read_at timestamptz,
  primary key (conversation_id, user_id)
);
create index if not exists conversation_members_user_idx on public.conversation_members (user_id, conversation_id);

create table if not exists public.messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete restrict,
  body text not null check (char_length(body) between 1 and 10000),
  created_at timestamptz not null default now(),
  edited_at timestamptz,
  deleted_at timestamptz
);
create index if not exists messages_conversation_created_idx on public.messages (conversation_id, created_at desc);

create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  booking_id uuid not null unique references public.bookings(id) on delete restrict,
  payer_id uuid not null references public.profiles(id) on delete restrict,
  payee_id uuid not null references public.profiles(id) on delete restrict,
  provider text not null,
  provider_reference text unique,
  status text not null default 'pending'
    check (status in ('pending', 'authorized', 'paid', 'failed', 'refunded', 'partially_refunded')),
  amount numeric(10,2) not null check (amount > 0),
  platform_fee numeric(10,2) not null default 0 check (platform_fee >= 0),
  currency char(3) not null default 'ZAR' check (currency = 'ZAR'),
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists payments_payer_created_idx on public.payments (payer_id, created_at desc);
create index if not exists payments_payee_created_idx on public.payments (payee_id, created_at desc);

create table if not exists public.user_notification_preferences (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  email_messages boolean not null default true,
  email_booking_updates boolean not null default true,
  email_payment_updates boolean not null default true,
  push_messages boolean not null default true,
  push_booking_updates boolean not null default true,
  push_payment_updates boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  kind text not null,
  title text not null,
  body text not null default '',
  data jsonb not null default '{}'::jsonb,
  read_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists notifications_user_unread_idx on public.notifications (user_id, created_at desc) where read_at is null;

