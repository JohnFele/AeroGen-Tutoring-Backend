import { listApplications, reviewApplication, applicationDocument } from '../controllers/application.controller.js';
import { listStudents, studentDetails, editStudent } from '../controllers/studentAdmin.controller.js';
import { Router } from 'express';
import { authorize,authorizeRole } from '../middleware/auth.middleware.js';
import { adminData,listAdminTutors,editAdminTutor,tutorAudit } from '../controllers/tutorAdmin.controller.js';
import { adminContact,saveContact,listOpenings,saveOpening,deleteOpening,listEnquiries,enquiryDetails,updateEnquiry,replyToEnquiry } from '../controllers/siteAdmin.controller.js';
import { supportLimiter } from '../middleware/rateLimit.middleware.js';
const router=Router();
router.use(authorize,authorizeRole(['admin','superUser']));
router.use((req,res,next)=>{res.set('Cache-Control','no-store');next();});
router.get('/data',adminData);
router.get('/tutors',listAdminTutors);
router.get('/tutors/:id/audit',tutorAudit);
router.patch('/tutors/:id',editAdminTutor);
router.get('/applications', listApplications);
router.patch('/applications/:id/review', reviewApplication);
router.get('/applications/:id/documents/:documentId', applicationDocument);
router.get('/students', listStudents);
router.get('/students/:id', studentDetails);
router.patch('/students/:id', editStudent);
router.get('/contact-details',adminContact);
router.put('/contact-details',saveContact);
router.get('/openings',listOpenings);
router.post('/openings',saveOpening);
router.patch('/openings/:id',saveOpening);
router.delete('/openings/:id',deleteOpening);
router.get('/enquiries',listEnquiries);
router.get('/enquiries/:id',enquiryDetails);
router.patch('/enquiries/:id',updateEnquiry);
router.post('/enquiries/:id/replies',supportLimiter,replyToEnquiry);
export default router;
