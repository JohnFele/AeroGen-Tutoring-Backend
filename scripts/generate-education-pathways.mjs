import { writeFileSync } from 'node:fs'
import { pathways } from '../src/data/educationPathways.mjs'

const entries = pathways.map((pathway, sort_order) => {
  const trim = (subjects, defaultUrl) => subjects.map(({ url, ...subject }) => ({
    ...subject, ...(url && url !== defaultUrl ? { url } : {}),
  }))
  return {
    ...pathway, sort_order,
    ...(pathway.sharedSubjects ? { sharedSubjects:trim(pathway.sharedSubjects,pathway.sources[0]?.url) } : {}),
    ...(pathway.subjects ? { subjects:Object.fromEntries(Object.entries(pathway.subjects).map(([level,subjects]) =>
      [level,trim(subjects,pathway.stages?.[level]?.url ?? pathway.sources[0]?.url)])) } : {}),
  }
})
const categoryByGroup = {
  Languages:'languages', Mathematics:'mathematics', 'Life Skills':'primary-foundations',
  'General education':'primary-foundations', Sciences:'natural-sciences', 'Commerce and services':'business-economics',
  Technology:'technology-coding', 'Humanities and wellbeing':'humanities-social-sciences', Arts:'creative-arts-music',
  'Specialist options':'vocational-technical',
}
const topics = Object.entries(pathways[0].subjects).flatMap(([level, subjects]) => subjects.map(({ name, group }) => ({
  name, level, category:categoryByGroup[group],
  slug:name === 'English First Additional Language' ? 'english-first-additional' : name.toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,''),
})))
const schema = `-- Generated by scripts/generate-education-pathways.mjs.
create table public.education_pathways (
  code text primary key check (code ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  sort_order integer not null check (sort_order>=0),
  details jsonb not null check (jsonb_typeof(details)='object' and details->>'code'=code)
);
alter table public.education_pathways enable row level security;
revoke all on public.education_pathways from public,anon,authenticated;
grant select on public.education_pathways to anon,authenticated;
create policy "Education pathways are public" on public.education_pathways for select to anon,authenticated using (true);
insert into public.education_pathways(code,sort_order,details)
select item->>'code',(item->>'sort_order')::integer,item
from jsonb_array_elements($pathways$${JSON.stringify(entries)}$pathways$::jsonb) as entry(item);

-- Add canonical CAPS subjects while preserving existing tutor subject IDs.
with curriculum_topics as (
  select * from jsonb_to_recordset($topics$${JSON.stringify(topics)}$topics$::jsonb)
    as topic(name text,level text,category text,slug text)
), added as (
  insert into public.subjects(name,slug,category,sort_order)
  select distinct on (t.slug) t.name,t.slug,c.name,500
  from curriculum_topics t join public.subject_categories c on c.slug=t.category
  order by t.slug,t.name
  on conflict do nothing returning id,slug
), catalog as (
  select id,slug from public.subjects
  union all
  select id,slug from added
)
insert into public.subject_education_levels(subject_id,level_code)
select s.id,t.level from curriculum_topics t join catalog s on s.slug=t.slug
on conflict do nothing;
notify pgrst,'reload schema';
`

const migration = process.argv[2] ?? '20261106103624_education_pathways.sql'
if (!/^\d{14}_education_pathways\.sql$/.test(migration)) throw new Error('Expected an education_pathways migration filename')
writeFileSync(new URL(`../supabase/migrations/${migration}`, import.meta.url), schema)
writeFileSync(new URL('../../../Frontend/AeroGen-Tutoring/src/data/educationPathways.json', import.meta.url), JSON.stringify(entries) + '\n')
